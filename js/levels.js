const GOAL_TYPES = ['collect', 'jelly', 'dino', 'clear', 'order', 'chocoGot', 'bake', 'mix'];
export const CLEAR_KINDS = ['frost', 'choco', 'cage', 'shell', 'gate', 'balloon', 'jar', 'egg', 'lantern'];
export const ORDER_SPECIALS = ['stripe', 'wrap', 'bomb', 'fish'];
export const isOrderKey = w => w === 'combo' || ORDER_SPECIALS.includes(w)
  || (/^[a-z]+\+[a-z]+$/.test(w) && w.split('+').every(x => ORDER_SPECIALS.includes(x)) && w.split('+').sort().join('+') === w);
export function goalParts(L) {
  const g = (L && L.goal) || {}, out = [];
  const items = g.type === 'collect' || g.type === 'mix' ? g.items || {} : {};
  for (const [id, n] of Object.entries(items)) out.push({ kind: 'collect', id, need: n });
  if (g.type === 'jelly' || (g.type === 'mix' && g.jelly)) out.push({ kind: 'jelly' });
  const dinos = g.type === 'dino' ? g.count : g.type === 'mix' ? g.dinos : 0;
  if (dinos > 0) out.push({ kind: 'dino', need: dinos });
  for (const w of (g.type === 'clear' ? g.what : g.type === 'mix' ? g.clear : null) || []) out.push({ kind: w });
  const orders = g.type === 'order' || g.type === 'mix' ? g.orders || {} : {};
  for (const [what, n] of Object.entries(orders)) out.push({ kind: 'order', what, need: n });
  const got = g.type === 'chocoGot' ? g.count : g.type === 'mix' ? g.chocoGot : 0;
  if (got > 0) out.push({ kind: 'chocoGot', need: got });
  const bakes = g.type === 'bake' ? g.count : g.type === 'mix' ? g.bakes : 0;
  if (bakes > 0) out.push({ kind: 'bake', need: bakes });
  if (!out.length) out.push({ kind: 'score' });
  return out;
}
// 這一關要給引擎的機關選項
export function mechOpts(L) {
  const o = {};
  if (!L) return o;
  if (Array.isArray(L.obstacles)) o.obstacles = L.obstacles;
  if (Array.isArray(L.portals)) o.portals = L.portals;
  if (Array.isArray(L.belts)) o.belts = L.belts;
  if (L.licorice) o.licorice = { ...L.licorice };
  if (L.alarm) o.alarm = { ...L.alarm };
  if (L.pot) o.pot = { ...L.pot };
  if (L.tickets) o.tickets = { ...L.tickets };
  if (L.jar) o.jar = { ...L.jar };
  const d = goalParts(L).find(p => p.kind === 'dino');
  if (d) o.dinos = { total: d.need, onBoard: 2, rate: 0.35, ...(L.dinos || {}) };
  return o;
}
// 一個目標還差多少（stats = engine.stats；kindOf：毛絨 id → 方塊種類）
export function partLeft(part, stats, kindOf) {
  const st = stats || {};
  switch (part.kind) {
    case 'collect': return Math.max(0, part.need - ((st.cleared || {})[kindOf(part.id)] || 0));
    case 'jelly': return Math.max(0, st.jellyLeft | 0);
    case 'dino': return Math.max(0, part.need - (st.dinosOut | 0));
    case 'frost': return Math.max(0, st.frostLeft | 0);
    case 'choco': return Math.max(0, st.chocoLeft | 0);
    case 'cage': return Math.max(0, st.locksLeft | 0);
    case 'shell': return Math.max(0, st.shellLeft | 0);
    case 'gate': return Math.max(0, st.gateLeft | 0);
    case 'balloon': return Math.max(0, st.balloonLeft | 0);
    case 'jar': return Math.max(0, st.jarLeft | 0);
    case 'egg': return Math.max(0, st.eggLeft | 0);
    case 'lantern': return Math.max(0, st.lanternLeft | 0);
    case 'bake': return Math.max(0, part.need - ((st.prog || {}).bakes | 0));
    case 'order': {
      const done = ORDER_SPECIALS.includes(part.what) ? (st.made || {})[part.what]
        : part.what === 'combo' ? st.comboCount : (st.combos || {})[part.what];
      return Math.max(0, part.need - (done | 0));
    }
    case 'chocoGot': return Math.max(0, part.need - (st.chocoGot | 0));
    default: return 0;
  }
}
// 目標達成了沒（分數關：到了過關分數）
export function goalDone(L, stats, score, kindOf) {
  const parts = goalParts(L);
  if (parts[0].kind === 'score') return score >= passScore(L);
  return parts.every(p => partLeft(p, stats, kindOf) <= 0);
}
// 過關分數（分數關）/ 完成目標時保底的分數（目標關）
export function passScore(L) {
  return (L && Array.isArray(L.stars) && L.stars[0]) || (L && L.goal && L.goal.target) || 0;
}
export function starsFor(L, score) {
  const thr = (L && L.stars) || [];
  return Math.max(1, Math.min(3, thr.filter(s => score >= s).length));
}

// ---------- 檢查 ----------
// 回傳問題清單（空陣列 = 沒問題）。pieceIds 可以傳 PIECES.map(p => p.id)，預設是目前的六隻。
export function validateLevels(levels = LEVELS, pieceIds = ALL_IDS) {
  const out = [];
  const DEF_ROWS = 9, DEF_COLS = 7;   // 長條盤面（像 Candy Crush）
  if (!Array.isArray(levels) || !levels.length) return ['LEVELS 是空的'];
  if (levels.length < 12 || levels.length > 1000) out.push(`關卡數 ${levels.length}（SPEC：12–1000）`);
  const seenSeeds = new Set();
  levels.forEach((L, i) => {
    const tag = `第 ${i + 1} 關`;
    const bad = msg => out.push(`${tag}：${msg}`);
    const ROWS = (L && L.rows) || DEF_ROWS, COLS = (L && L.cols) || DEF_COLS;
    if (!L || typeof L !== 'object') { bad('不是物件'); return; }
    if (L.id !== i + 1) bad(`id 應該是 ${i + 1}，現在是 ${L.id}`);
    if (!Number.isInteger(L.moves) || L.moves < 5 || L.moves > 60) bad(`moves 不合理：${L.moves}`);
    if (!Number.isInteger(L.seed) || L.seed <= 0) bad(`seed 要是正整數：${L.seed}`);
    else if (seenSeeds.has(L.seed)) bad(`seed ${L.seed} 重複`);
    else seenSeeds.add(L.seed);
    if (L.antiCascade != null && !(typeof L.antiCascade === 'number' && L.antiCascade >= 0 && L.antiCascade <= 1)) bad(`antiCascade 要在 0–1：${L.antiCascade}`);
    if (L.hint != null && (typeof L.hint !== 'string' || !L.hint.trim() || L.hint.length > 30)) bad('hint 要是一句短短的字');

    // kinds
    const kinds = Array.isArray(L.kinds) ? L.kinds : [];
    if (kinds.length < 4 || kinds.length > 6) bad(`kinds 要 4–6 種（現在 ${kinds.length}）`);
    if (new Set(kinds).size !== kinds.length) bad('kinds 有重複');
    kinds.forEach(k => { if (!pieceIds.includes(k)) bad(`不認識的毛絨 id：${k}`); });
    // 4 色的窄盤面放不下全部三隻掃描毛絨（收集目標要優先），至少要有一隻
    if (SCANNED.some(k => pieceIds.includes(k)) && !SCANNED.some(k => kinds.includes(k))) bad('至少要有一隻掃描毛絨');

    // stars
    const st = L.stars;
    if (!Array.isArray(st) || st.length !== 3 || !st.every(v => Number.isInteger(v) && v > 0)) bad('stars 要是三個正整數');
    else if (!(st[0] < st[1] && st[1] < st[2])) bad(`stars 要遞增：${st.join(', ')}`);

    // mask
    let cells = null;
    if (L.mask != null) {
      if (!Array.isArray(L.mask) || L.mask.length !== ROWS || !L.mask.every(r => typeof r === 'string' && r.length === COLS)) {
        bad(`mask 要是 ${ROWS} 個長度 ${COLS} 的字串`);
      } else {
        cells = L.mask.map(r => [...r].map(ch => ch !== '.'));
      }
    }
    const isCell = (r, c) => r >= 0 && r < ROWS && c >= 0 && c < COLS && (cells ? cells[r][c] : true);
    let nCells = 0;
    for (let r = 0; r < ROWS; r++) for (let c = 0; c < COLS; c++) if (isCell(r, c)) nCells++;
    if (nCells < 30) bad(`格子太少（${nCells}）`);
    // 每個格子至少要在一段長度 ≥3 的橫線或直線上，不然永遠消不到
    const runLen = (r, c, dr, dc) => {
      let n = 1;
      for (let k = 1; isCell(r + dr * k, c + dc * k); k++) n++;
      for (let k = 1; isCell(r - dr * k, c - dc * k); k++) n++;
      return n;
    };
    const dead = [];
    for (let r = 0; r < ROWS; r++) for (let c = 0; c < COLS; c++) {
      if (isCell(r, c) && runLen(r, c, 0, 1) < 3 && runLen(r, c, 1, 0) < 3) dead.push(`(${r},${c})`);
    }
    if (dead.length) bad(`這些格子永遠湊不成三連：${dead.join(' ')}`);
    // 每一欄的格子要能從上面補到（中間有洞沒關係，方塊會穿過去）
    // → 只要盤面的格子都在 0..ROWS-1 就一定補得到，這裡不用另外檢查。

    // jelly
    let layers = 0;
    if (L.jelly != null) {
      if (!Array.isArray(L.jelly) || L.jelly.length !== ROWS || !L.jelly.every(r => typeof r === 'string' && r.length === COLS)) {
        bad(`jelly 要是 ${ROWS} 個長度 ${COLS} 的字串`);
      } else {
        for (let r = 0; r < ROWS; r++) for (let c = 0; c < COLS; c++) {
          const ch = L.jelly[r][c];
          if (ch === '.' || ch === '0') continue;
          if (ch !== '1' && ch !== '2') { bad(`jelly (${r},${c}) 只能是 . 0 1 2，現在是 '${ch}'`); continue; }
          if (!isCell(r, c)) { bad(`jelly (${r},${c}) 放在洞上`); continue; }
          layers += Number(ch);
        }
      }
    }

    // goal
    const g = L.goal || {};
    if (g.type === 'score') {
      if (!Number.isInteger(g.target) || g.target <= 0) bad('score 目標要是正整數');
      else if (Array.isArray(st) && st[0] !== g.target) bad(`score 關的 stars[0]（${st[0]}）要等於目標（${g.target}）`);
      if (layers) bad('score 關不要放果凍（目標面板不會顯示）');
    } else if (g.type === 'collect') {
      const items = g.items && typeof g.items === 'object' ? Object.entries(g.items) : [];
      if (!items.length || items.length > 3) bad('collect 要 1–3 種');
      items.forEach(([k, n]) => {
        if (!kinds.includes(k)) bad(`collect 的 ${k} 不在 kinds 裡`);
        if (!Number.isInteger(n) || n <= 0) bad(`collect ${k} 的數量要是正整數`);
      });
      if (layers) bad('collect 關不要放果凍（目標面板不會顯示）');
    } else if (g.type === 'jelly') {
      if (!layers) bad('jelly 關卻沒有果凍');
    } else if (!['dino', 'clear', 'order', 'chocoGot', 'bake', 'mix'].includes(g.type)) {
      bad(`不認識的目標類型：${g.type}`);
    }

    // 盤面機關
    const obs = L.obstacles;
    const has = { L: 0, C: 0, S: 0, D: 0, E: 0, A: 0, P: 0, frost: 0, shell: 0, gift: 0, gate: 0, T: 0, O: 0, jar: 0, U: 0, K: 0 };
    const strings = {};
    const NEWFIX = 'GQabcdUmnopK', FIXED = '123CXYP' + NEWFIX;
    if (obs != null) {
      if (!Array.isArray(obs) || obs.length !== ROWS || !obs.every(r => typeof r === 'string' && r.length === COLS)) bad(`obstacles 要是 ${ROWS} 個長度 ${COLS} 的字串`);
      else for (let r = 0; r < ROWS; r++) for (let c = 0; c < COLS; c++) {
        const ch = obs[r][c];
        if (ch === '.') continue;
        if (!'LCSDEA123XYP-|WBGQTOabcdUmnopK'.includes(ch)) { bad(`obstacles (${r},${c}) 不認識的字 '${ch}'`); continue; }
        if (!isCell(r, c)) { bad(`obstacles (${r},${c}) 放在洞上`); continue; }
        if ('123'.includes(ch)) has.frost += +ch; else if ('XY'.includes(ch)) has.shell += ch === 'Y' ? 2 : 1; else if ('-|WB'.includes(ch)) has.gift++;
        else if ('GQ'.includes(ch)) has.gate += ch === 'Q' ? 2 : 1; else if ('abcd'.includes(ch)) has.jar++;
        else if ('mnop'.includes(ch)) strings[ch] = (strings[ch] || 0) + 1; else has[ch]++;
        if (NEWFIX.includes(ch) && isCell(r + 1, c) && !FIXED.includes(obs[r + 1][c])
          && ![c - 1, c + 1].some(x => isCell(r, x) && !FIXED.includes(obs[r][x]) && obs[r][x] !== 'L')) bad(`obstacles (${r},${c}) 底下的格子補不到（正下方和左右都擋住了）`);
        const jl = L.jelly && L.jelly[r] && L.jelly[r][c] && L.jelly[r][c] !== '.';
        if (jl && '123CXYP'.includes(ch)) bad(`obstacles (${r},${c}) 糖霜 / 巧克力 / 硬殼 / 巧克力壺不要蓋在果凍上`);
        // 糖霜、巧克力底下要是盤面外或同樣不會動的東西（不然底下那格什麼都掉不進去）
        if ('123'.includes(ch) && isCell(r + 1, c) && !'123C'.includes(obs[r + 1][c])) bad(`obstacles (${r},${c}) 糖霜底下還有空格子`);
        if ('XY'.includes(ch) && isCell(r + 1, c) && !'123CXY'.includes(obs[r + 1][c])) bad(`obstacles (${r},${c}) 硬殼底下還有空格子`);
        if (ch === 'P' && isCell(r + 1, c) && !'123CXYP'.includes(obs[r + 1][c])) bad(`obstacles (${r},${c}) 巧克力壺底下還有空格子`);
      }
    }
    for (const q of L.portals || []) {
      if (!Array.isArray(q) || q.length !== 4 || !isCell(q[0], q[1]) || !isCell(q[2], q[3])) bad(`portal ${JSON.stringify(q)} 要在格子上`);
      else if (isCell(q[0] + 1, q[1])) bad(`portal ${JSON.stringify(q)} 的入口下面還有格子`);
      else if (isCell(q[2] - 1, q[3])) bad(`portal ${JSON.stringify(q)} 的出口上面還有格子`);
    }
    // 輸送帶：每條是一串 [r, c]，相鄰兩格要上下左右挨著（只有最後一格回到第一格可以跳過去）；
    // 帶子上不能放不會動的東西（籠子、保鮮膜、糖霜、巧克力、硬殼、巧克力壺），不然整條帶子都不會動
    if (L.belts != null) {
      const used = new Set();
      if (!Array.isArray(L.belts) || !L.belts.length) bad('belts 要是一串輸送帶');
      else L.belts.forEach((b, bi) => {
        const nm = `輸送帶 ${bi + 1}`;
        if (!Array.isArray(b) || b.length < 2 || !b.every(q => Array.isArray(q) && q.length === 2 && Number.isInteger(q[0]) && Number.isInteger(q[1]))) { bad(`${nm} 要是至少兩個 [r, c]`); return; }
        b.forEach((q, k) => {
          const [r, c] = q, id = r * 100 + c;
          if (!isCell(r, c)) bad(`${nm} 的 (${r},${c}) 不在格子上`);
          if (used.has(id)) bad(`${nm} 的 (${r},${c}) 重複了`);
          used.add(id);
          if (k && Math.abs(r - b[k - 1][0]) + Math.abs(c - b[k - 1][1]) !== 1) bad(`${nm} 的 (${b[k - 1].join(',')}) → (${r},${c}) 沒有挨著`);
          const ch = Array.isArray(obs) && obs[r] ? obs[r][c] : '.';
          if (ch && 'L123CXYP-|WBGQabcdUmnopK'.includes(ch)) bad(`${nm} 的 (${r},${c}) 上面有不會動的東西 '${ch}'`);
        });
      });
    }
    if (L.licorice != null && !(L.licorice.rate > 0 && L.licorice.rate <= 0.2 && L.licorice.max >= 1 && L.licorice.max <= 8)) bad('licorice 要 { rate: 0–0.2, max: 1–8 }');
    if (L.alarm != null) {
      const a = L.alarm, rate = a.rate ?? 0, max = a.max ?? 2;
      if (!(Number.isInteger(a.timer) && a.timer >= 3 && a.timer <= 30)) bad('alarm.timer 要是 3–30 的整數');
      if (!(rate >= 0 && rate <= 0.2 && Number.isInteger(max) && max >= 1 && max <= 4)) bad('alarm 要 { rate: 0–0.2, max: 1–4 }');
      if (!has.A && !(rate > 0)) bad('有 alarm 設定，盤面上卻沒有鬧鐘，也不會掉鬧鐘');
    }
    if (has.A && L.alarm == null) bad('盤面上有鬧鐘（A），要寫 alarm: { timer }');
    if (L.pot != null && !(Number.isInteger(L.pot.max) && L.pot.max >= 3 && L.pot.max <= 12)) bad('pot 要 { max: 3–12 }');
    if (L.pot != null && !has.P) bad('有 pot 設定，盤面上卻沒有巧克力壺（P）');
    if (L.tickets != null && !(L.tickets.rate > 0 && L.tickets.rate <= 0.2 && Number.isInteger(L.tickets.max ?? 3) && (L.tickets.max ?? 3) >= 1 && (L.tickets.max ?? 3) <= 4)) bad('tickets 要 { rate: 0–0.2, max: 1–4 }');
    if (L.tickets != null && !has.gate) bad('有 tickets 設定，盤面上卻沒有票閘');
    if (has.gate && L.tickets == null && has.T < has.gate) bad(`票閘要 ${has.gate} 張車票，盤面上只有 ${has.T} 張，也不會掉車票`);
    if (has.T && !has.gate) bad('盤面上有車票（T），卻沒有票閘');
    if (L.jar != null && !(Number.isInteger(L.jar.need) && L.jar.need >= 3 && L.jar.need <= 9)) bad('jar 要 { need: 3–9 }');
    if (L.jar != null && !has.jar) bad('有 jar 設定，盤面上卻沒有蜂蜜罐');
    for (const [k, n] of Object.entries(strings)) if (n < 2) bad(`燈籠串 ${k} 只有 ${n} 個燈籠（一串至少 2 個）`);
    const parts = goalParts(L);
    for (const part of parts) {
      if (part.kind === 'dino' && !(Number.isInteger(part.need) && part.need > 0 && part.need <= 8)) bad('救龍龍的數量要 1–8');
      if (part.kind === 'frost' && !has.frost) bad('要清糖霜，盤面上卻沒有糖霜');
      if (part.kind === 'choco' && !has.C) bad('要清巧克力，盤面上卻沒有巧克力');
      if (part.kind === 'choco' && has.P) bad('有巧克力壺會一直噴，不要用「清光巧克力」當目標');
      if (part.kind === 'cage' && !has.L) bad('要開籠子，盤面上卻沒有鐵籠子');
      if (part.kind === 'shell' && !has.shell) bad('要打破硬殼，盤面上卻沒有硬殼');
      if (part.kind === 'jelly' && !layers) bad('目標有果凍，盤面上卻沒有果凍');
      if (part.kind === 'gate' && !has.gate) bad('要打開票閘，盤面上卻沒有票閘');
      if (part.kind === 'balloon' && !has.O) bad('要放走熱氣球，盤面上卻沒有熱氣球');
      if (part.kind === 'jar' && !has.jar) bad('要裝滿蜂蜜罐，盤面上卻沒有蜂蜜罐');
      if (part.kind === 'egg' && !has.U) bad('要孵驚喜蛋，盤面上卻沒有驚喜蛋');
      if (part.kind === 'lantern' && !Object.keys(strings).length) bad('要點燈籠，盤面上卻沒有燈籠');
      if (part.kind === 'bake') {
        if (!(Number.isInteger(part.need) && part.need > 0 && part.need <= 12)) bad('烤箱的次數要 1–12');
        if (!has.K) bad('要烤東西，盤面上卻沒有烤箱');
      }
      if (!['collect', 'jelly', 'dino', 'order', 'chocoGot', 'bake', 'score'].includes(part.kind) && !CLEAR_KINDS.includes(part.kind)) bad(`不認識的清除目標：${part.kind}`);
      if (part.kind === 'collect' && !kinds.includes(part.id)) bad(`collect 的 ${part.id} 不在 kinds 裡`);
      if (part.kind === 'order') {
        if (!isOrderKey(part.what)) bad(`不認識的訂單：${part.what}`);
        if (!(Number.isInteger(part.need) && part.need > 0 && part.need <= 10)) bad(`訂單 ${part.what} 的數量要 1–10`);
      }
      if (part.kind === 'chocoGot') {
        if (!(Number.isInteger(part.need) && part.need > 0 && part.need <= 30)) bad('收集巧克力的數量要 1–30');
        if (!has.C && !has.P) bad('要收集巧克力，盤面上卻沒有巧克力或巧克力壺');
      }
    }
    if (g.type === 'mix' && parts.length < 2) bad('mix 王關至少要兩個目標');
    if (['dino', 'clear', 'order', 'chocoGot', 'bake'].includes(g.type) && layers) bad(`${g.type} 關不要放果凍（目標面板不會顯示）`);
    if (has.D && !parts.some(q => q.kind === 'dino')) bad('盤面上有龍龍，目標卻沒有救龍龍');
  });
  return out;
}
